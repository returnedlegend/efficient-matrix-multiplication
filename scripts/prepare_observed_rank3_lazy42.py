"""Freeze continuation chunks from existing observed catalogues; no target queries."""
import argparse
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path
import shutil
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from mmsearch.recombine import digest
from scripts.freeze_campaign_dictionary import freeze,json_bytes,read_json
ROOT=Path(__file__).resolve().parents[1]
SHA=lambda path:hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--prepared-dir',type=Path,required=True);p.add_argument('--pilot-dir',type=Path,required=True)
    p.add_argument('--output-dir',type=Path,required=True);p.add_argument('--chunk-size',type=int,default=2000);a=p.parse_args()
    b=a.prepared_dir.resolve();pilot=a.pilot_dir.resolve();out=a.output_dir.resolve()
    if not 1<=a.chunk_size<=2000:p.error('chunk size outside1..2000')
    integrity=read_json((b/'integrity.json').read_bytes())
    for name,expected in integrity.items():
        if SHA(b/name)!=expected:raise ValueError('old preparation hash mismatch: '+name)
    cases=read_json((b/'cases.json').read_bytes());config=read_json((pilot/'config.json').read_bytes());cursor=read_json((pilot/'cursor.json').read_bytes())
    if config['prepared_integrity_sha256']!=SHA(b/'integrity.json') or config['plan_sha256']!=digest(cases) or config['controls_only']:
        raise ValueError('pilot source/plan mismatch')
    if cursor['config_sha256']!=digest(config) or cursor['next_index']!=len(cases):raise ValueError('pilot not exactly completed')
    exclusions=[];excluded=set()
    for case in cases:
        path=pilot/'cases'/case['id']/'result.json';result=read_json(path.read_bytes())
        if (result['status']!='NO_ONE_SUBSPACE_GAIN' or not result.get('complete_for_requested_bound') or
            result['searched_bound']!=case['weight_bound'] or result['quotient_sha256']!=case['quotient_sha256'] or
            not result['worker_reaped'] or result['worker_exitcode']!=0):raise ValueError('pilot exact completion missing')
        key=(case['source_id'],tuple(case['space']))
        if key in excluded:raise ValueError('duplicate pilot identity')
        excluded.add(key);exclusions.append(dict(case=case,result_sha256=SHA(path),result=result))
    out.mkdir(parents=True,exist_ok=False);freeze(out/'pilot-exclusions.json',json_bytes(exclusions));sources={};chunks=[];metrics=[]
    for source in sorted({case['source_id'] for case in cases}):
        for name in ('system.json','active-certificate.json','baseline.verification.json'):
            freeze(out/'sources'/source/name,(b/'sources'/source/name).read_bytes())
        catalog=gzip.decompress((b/'catalogs'/(source+'.json.gz')).read_bytes());full=json.loads(catalog)
        pending=[];hist=Counter()
        for ordinal,item in enumerate(full):
            hist[item['k']]+=1
            if 4<=item['k']<=6 and (source,tuple(item['space'])) not in excluded:
                pending.append(dict(full_catalog_ordinal=ordinal,space=item['space'],basis_values=item['basis_values'],k=item['k'],weight_bound=item['k']-1))
        sources[source]=dict(system_sha256=SHA(out/'sources'/source/'system.json'),catalog_compressed_sha256=SHA(b/'catalogs'/(source+'.json.gz')),
            original_catalog_content_sha256=digest(full),catalogued=len(full),remaining=len(pending),k_histogram=dict(hist))
        for offset in range(0,len(pending),a.chunk_size):
            items=pending[offset:offset+a.chunk_size];chunk_id=f'{source}-{offset//a.chunk_size:03d}';name='plans/'+chunk_id+'.json.gz'
            freeze(out/name,gzip.compress(json_bytes(items),compresslevel=1,mtime=0))
            chunks.append(dict(id=chunk_id,source_id=source,source_offset=offset,count=len(items),plan=name,plan_sha256=digest(items),compressed_sha256=SHA(out/name)))
        metrics.append(dict(source_id=source,remaining=len(pending),pilot_excluded=sum(c['case']['source_id']==source for c in exclusions),k_histogram=dict(hist)))
    plan=dict(version=1,decoder='rank3-weight5-lazy-logical-ledger-v1',sources=sources,chunks=chunks,pilot_exclusions_sha256=SHA(out/'pilot-exclusions.json'),
        original_prepared_integrity_sha256=SHA(b/'integrity.json'),original_pilot_config_sha256=SHA(pilot/'config.json'),original_pilot_cursor_sha256=SHA(pilot/'cursor.json'),
        supported_total=47740,remaining=sum(c['count'] for c in chunks),scope='Explicit observed3D spaces generated by triples of observed W, fixed source P/W; exact groupweight<=5 only. k3 necessary bound and k>=7 nonclosed remain separate.')
    if plan['remaining']!=47722 or len(exclusions)!=18:raise ValueError('unexpected campaign remaining count')
    freeze(out/'plan.json',json_bytes(plan));freeze(out/'METRICS.json',json_bytes(metrics))
    for name in ('mmsearch','scripts'):
        for path in sorted((ROOT/name).rglob('*.py')):freeze(out/'code'/path.relative_to(ROOT),path.read_bytes())
    test=ROOT/'tests/test_observed_rank3_lazy42.py'
    if test.exists():freeze(out/'code/tests'/test.name,test.read_bytes());freeze(out/'code/tests/__init__.py',b'')
    bindings={str(path.relative_to(out)):SHA(path) for path in sorted(out.rglob('*')) if path.is_file()};freeze(out/'integrity.json',json_bytes(bindings))
    first=[c['id'] for c in chunks if c['source_offset']==0]
    command=['python3','-B',str(out/'code/scripts/campaign_observed_rank3_lazy42.py'),'--prepared-dir',str(out),'--output-dir',str(out.parent/'observed-rank3-continuation6000-001'),
        '--seconds','840','--per-case-seconds','20','--memory-mb','1024','--guard-state',str(out.parent/'operations-v3/state.json')]
    for key in first:command.extend(['--chunk-id',key])
    freeze(out/'PROPOSED-JOB.json',json_bytes(dict(id='observed-rank3-continuation6000-001',enabled=False,cpu=1,memory_mb=1024,seconds=900,command=command)))
    print(json.dumps(dict(status='PREPARED',remaining=plan['remaining'],chunks=len(chunks),first_job_cases=sum(c['count'] for c in chunks if c['id'] in first),target_queries=0)))


if __name__=='__main__':main()
